import assert from 'node:assert/strict'
import fs from 'node:fs'
import path from 'node:path'

export async function cleanupUiSmoke({ browser, evaluate, waitFor, click, key, delay, screenshotDirectory, first, output }) {
  const capture = async name => {
    await delay(550)
    const shot = await browser.send('Page.captureScreenshot', { format: 'png' })
    const location = path.join(screenshotDirectory, `m2-h3-${name}.png`)
    fs.writeFileSync(location, Buffer.from(shot.data, 'base64'))
    assert.equal(await evaluate("[...document.querySelectorAll('[role=dialog],[data-cleanup-panel],[data-cleanup-footer]')].every(el=>el.scrollWidth<=el.clientWidth+1)"), true, 'No horizontal overflow: ' + JSON.stringify(await evaluate("[...document.querySelectorAll('[role=dialog] *')].filter(el=>el.scrollWidth>el.clientWidth+1 && el.getClientRects().length).slice(0,8).map(el=>({tag:el.tagName,cls:el.className,width:el.clientWidth,scroll:el.scrollWidth}))")))
    assert.equal(await evaluate("(()=>{const el=document.querySelector('[data-cleanup-footer]');if(!el)return true;const r=el.getBoundingClientRect();return r.top>0&&r.bottom<=innerHeight})()"), true, 'Fixed footer is visible')
    console.log(`CAPTURE 1024x700 cleanup ${name}: ${location}`)
  }
  const themes = async name => {
    for (const theme of ['light', 'dark']) {
      await evaluate(`await hopline.settings.update({theme:${JSON.stringify(theme)}});await testState.reloadCatalog()`)
      await capture(`${name}-${theme}`)
    }
  }
  const enterPassword = async () => {
    await waitFor("document.querySelector('[data-cleanup-panel] input[type=password]')")
    await evaluate("document.querySelector('[data-cleanup-panel] input[type=password]').focus()")
    await browser.send('Input.insertText', { text: 'cleanup-smoke-private' })
    await key('Enter')
  }
  const ready = () => waitFor("document.querySelector('[data-cleanup-ready]')")
  const select = async ids => {
    await click('[data-cleanup-select=none]')
    await evaluate(`${JSON.stringify(ids)}.forEach(id=>document.querySelector('[data-cleanup-item="'+id+'"] input').click())`)
  }
  const confirm = async () => {
    await click('[data-cleanup-footer] button.bg-accent')
    await waitFor("document.querySelector('[data-cleanup-confirm]')")
    await click('[role=dialog][aria-label="确认清理"] button.bg-accent')
  }
  const cleanupText = () => evaluate("document.querySelector('[data-cleanup-panel]').innerText")
  first.cleanup.enabled = true
  await evaluate("window.testCleanupNav=await import('/src/state/runbook.ts');await hopline.collect.run(fileHost.id);testCleanupNav.openCleanup(fileHost.id)")
  await waitFor("document.querySelector('[data-cleanup-panel] input[type=password]')")
  assert.equal(first.cleanup.checks, 0, 'No cleanup checks before password')
  assert.equal(await evaluate("document.querySelector('[data-cleanup-ready]')"), null)
  await themes('password')
  // Hold an actual SSH read so screenshots show a real in-flight scan, then cancel it.
  first.cleanup.holdRead = 'check'
  await enterPassword()
  for (let tries=0; !first.cleanup.heldRead && tries<100; tries++) await delay(20)
  assert.ok(first.cleanup.heldRead)
  await themes('scanning')
  await evaluate("[...document.querySelectorAll('[data-cleanup-stage] button')].find(b=>b.textContent==='取消').click()")
  await waitFor("document.querySelector('[role=alert]')?.innerText.includes('已取消')")
  assert.equal(await evaluate("document.querySelector('input[type=password]').value"), '')
  await enterPassword(); await ready()
  assert.equal(first.cleanup.checks, 13)
  assert.equal(first.cleanup.invalidStdin, 0); assert.equal(first.cleanup.commandLeaks, 0)
  assert.ok(!(await cleanupText()).includes('cleanup-smoke-private'))
  assert.equal(await evaluate("document.querySelectorAll('[data-cleanup-item] input:checked').length"), 6)
  assert.equal(await evaluate("document.querySelector('[data-cleanup-item=tmp-old] input').disabled"), true)
  assert.equal(await evaluate("document.querySelector('[data-cleanup-item=rotated-logs] input').checked"), false)
  assert.ok(await evaluate("document.querySelector('[data-cleanup-item=crash-reports] input').checked && document.querySelector('[data-cleanup-item=coredumps] input').checked"))
  assert.equal(await evaluate("document.querySelector('[data-cleanup-empty]').open"), false)
  assert.equal(await evaluate("document.querySelector('[data-cleanup-empty-item=dnf-cache]')!==null"), true)
  assert.equal(await evaluate("document.querySelector('[data-cleanup-group=docker] input').indeterminate"), true)
  assert.equal(await evaluate("document.querySelectorAll('[data-cleanup-ready] .gauge-bar').length"), 0)
  await click('[data-cleanup-group=docker] input')
  assert.equal(await evaluate("document.querySelectorAll('[data-cleanup-group=docker] [data-cleanup-item] input:checked').length"), 3)
  assert.equal(await evaluate("document.querySelector('[data-cleanup-group=docker]').open"), false, 'Category selection does not toggle expansion')
  await click('[data-cleanup-group=docker] input')
  assert.equal(await evaluate("document.querySelectorAll('[data-cleanup-group=docker] [data-cleanup-item] input:checked').length"), 0)
  await click('[data-cleanup-select=recommended]')
  await themes('ready')
  await evaluate("window.cleanupFreshRecord=testState.getState().snapshots[fileHost.id];testState.patch({snapshots:{...testState.getState().snapshots,[fileHost.id]:{...cleanupFreshRecord,updatedAt:Date.now()-7*86400000}}})")
  await waitFor("document.querySelector('[data-cleanup-historical]')")
  assert.ok(await evaluate("document.querySelector('[data-cleanup-ready]').innerText.includes('— 已用 —% · 预计 —%')"))
  await capture('historical-disk')
  await evaluate("testState.patch({snapshots:{...testState.getState().snapshots,[fileHost.id]:cleanupFreshRecord}})")
  await waitFor("!document.querySelector('[data-cleanup-historical]')")
  await evaluate("document.querySelector('[data-cleanup-group=docker] summary').click()")
  await themes('ready-expanded')
  await evaluate("[...document.querySelectorAll('[data-cleanup-item=docker-container-logs] button')].find(b=>b.textContent==='查看命令').click()")
  assert.ok(await evaluate("document.querySelector('[data-cleanup-log-drivers]').innerText.includes('Docker 自动轮转') && document.querySelector('[data-cleanup-log-drivers]').innerText.includes('系统归档日志')"))
  assert.equal(await evaluate("document.querySelectorAll('[data-cleanup-log-drivers] button,[data-cleanup-log-drivers] input').length"), 0)
  await evaluate("await hopline.settings.update({language:'en'});await testState.reloadCatalog()")
  assert.ok(await evaluate("document.querySelector('[data-cleanup-log-drivers]').innerText.includes('Docker rotates these logs automatically')"))
  await evaluate("[...document.querySelectorAll('[data-cleanup-item=docker-container-logs] button')].find(b=>b.textContent==='View command').click()")
  await capture('ready-dark-en')
  await evaluate("[...document.querySelectorAll('[data-cleanup-item=docker-container-logs] button')].find(b=>b.textContent==='View command').click();await hopline.settings.update({language:'zh'});await testState.reloadCatalog()")
  await evaluate("[...document.querySelectorAll('[data-cleanup-item=docker-container-logs] button')].find(b=>b.textContent==='查看命令').click()")
  await click('[data-cleanup-select=all]')
  assert.equal(await evaluate("document.querySelector('[data-cleanup-item=tmp-old] input').checked"), false)
  assert.equal(await evaluate("document.querySelector('[data-cleanup-group=docker] input').indeterminate"), false)
  assert.equal(await evaluate("document.querySelector('[data-cleanup-group=docker] input').checked"), true)
  await click('[data-cleanup-select=none]')
  assert.equal(await evaluate("document.querySelector('[data-cleanup-footer] button.bg-accent').disabled"), true)
  await click('[data-cleanup-select=recommended]')
  assert.equal(await evaluate("document.querySelectorAll('[data-cleanup-item] input:checked').length"), 6)
  await evaluate("document.querySelector('[data-cleanup-item=docker-container-logs] input').click()")
  await click('[data-cleanup-footer] button.bg-accent')
  assert.ok(await evaluate("document.querySelector('[data-cleanup-confirm]').innerText.includes('旧容器日志将永久丢失')"))
  await themes('confirmation-attention')
  assert.equal(first.cleanup.applies.length, 0, 'Opening confirmation never executes')
  await key('Escape'); await ready()
  assert.equal(first.cleanup.applies.length, 0, 'Canceling confirmation never executes')
  // Closing a preview discards the in-memory credential.
  await key('Escape'); await waitFor('!testState.getState().cleanupHost')
  await evaluate('testCleanupNav.openCleanup(fileHost.id)')
  await waitFor("document.querySelector('[data-cleanup-panel] input[type=password]')")
  assert.equal(await evaluate("document.querySelector('input[type=password]').value"), '')
  await enterPassword(); await ready()
  // A finding links to its diagnostic section, separate from the selection list.
  await evaluate("[...document.querySelectorAll('[data-cleanup-ready] button')].find(b=>b.textContent==='查看').click()")
  await waitFor("document.querySelector('[data-cleanup-diagnostic=deleted]')?.innerText.includes('worker')")
  assert.ok(await evaluate("document.querySelector('[data-cleanup-diagnostic=inodes]').innerText.includes('96%')"))
  assert.ok(await evaluate("document.querySelector('[data-cleanup-diagnostic=logs]').innerText.includes('已轮转')"))
  assert.equal(await evaluate("document.querySelectorAll('[data-cleanup-diagnostics] button').length"), 0)
  await evaluate("[...document.querySelectorAll('[data-cleanup-analysis] button')].find(b=>b.textContent==='分析目录').click()")
  await waitFor("document.querySelector('[data-cleanup-directories]')")
  assert.ok(await evaluate("document.querySelector('[data-cleanup-directories]').innerText.includes('35 GB')"))
  assert.equal(await evaluate("document.querySelector('[data-cleanup-directories] pre')"), null)
  await evaluate("document.querySelector('[data-cleanup-panel]').parentElement.scrollTop=0")
  await themes('analysis')
  await evaluate("document.querySelector('[data-cleanup-diagnostics]').scrollIntoView({block:'start'})")
  await themes('analysis-diagnostics')
  await evaluate("document.querySelector('[role=tab]').click()")
  await evaluate("window.cleanupSnapshot=testState.getState().snapshots[fileHost.id];testState.patch({snapshots:{[fileHost.id]:{...cleanupSnapshot,snapshot:{...cleanupSnapshot.snapshot,disk:{status:'complete',data:cleanupSnapshot.snapshot.disk.data.map(d=>({...d,usagePercent:d.mountpoint==='/data'?99:d.usagePercent}))}}}}})")
  assert.equal(await evaluate("document.querySelector('[data-cleanup-mount]').value"), '/', 'Reordering retains chosen mount')
  await evaluate("testState.patch({snapshots:{[fileHost.id]:{...cleanupSnapshot,snapshot:{...cleanupSnapshot.snapshot,disk:{status:'complete',data:cleanupSnapshot.snapshot.disk.data.filter(d=>d.mountpoint==='/')}}}}})")
  assert.equal(await evaluate("document.querySelector('[data-cleanup-mount]')"), null, 'Single mount has no switcher')
  await evaluate("testState.patch({snapshots:{[fileHost.id]:cleanupSnapshot}})")
  // APT executes while the later core dump item stays pending; stop must wait for APT.
  await select(['apt-cache', 'coredumps'])
  first.cleanup.holdApply = true
  await confirm()
  for (let tries=0; !first.cleanup.finishApply && tries<100; tries++) await delay(20)
  assert.ok(first.cleanup.finishApply)
  await themes('running')
  assert.ok((await cleanupText()).includes('第 1 项，共 2 项'))
  await evaluate("[...document.querySelectorAll('[data-cleanup-stage=running] button')].find(b=>b.textContent==='停止').click()")
  assert.equal(first.cleanup.applies.length, 0)
  assert.ok((await cleanupText()).includes('正在完成当前项目'))
  await capture('stopping-dark')
  await evaluate("document.querySelector('[role=dialog] button[aria-label]').click()")
  await waitFor("testState.getState().cleanupHidden && !document.querySelector('[data-cleanup-panel]')")
  assert.equal(first.cleanup.applies.length, 0, 'Hiding does not interrupt the current item')
  first.cleanup.finishApply(); first.cleanup.holdApply = false
  await waitFor("testState.getState().toasts.some(item=>item.action?.label==='查看结果')")
  await evaluate("[...document.querySelectorAll('button')].find(b=>b.textContent==='查看结果').click()")
  await waitFor("document.querySelector('[data-cleanup-results]')")
  assert.equal(await evaluate("testState.getState().toasts.some(item=>item.action?.label==='查看结果')"), false, 'Opening results dismisses its completion notice')
  assert.deepEqual(first.cleanup.applies, ['apt-cache'])
  assert.equal(first.cleanup.dfReads, 2, 'One target df reading on each side')
  assert.ok((await cleanupText()).includes('已释放 64 MB'))
  assert.ok(await evaluate("document.querySelector('[data-cleanup-comparison]').innerText.includes('92.0%') && document.querySelector('[data-cleanup-comparison]').innerText.includes('80.0%')"))
  assert.ok(await evaluate("document.querySelector('[data-cleanup-incomplete]').innerText.includes('你停止了清理')"))
  assert.deepEqual(await evaluate("(await hopline.oplog.list(fileHost.id)).find(row=>row.stepId==='apt-cache').cleanup"), { estimatedBytes: 67108864, actualBytes: 67108864 })
  assert.equal(await evaluate("JSON.stringify(await hopline.oplog.list(fileHost.id)).includes('cleanup-smoke-private')"), false)
  await themes('results-incomplete')
  // Rescan asks for a fresh password, then demonstrate a fully completed result.
  await evaluate("[...document.querySelectorAll('[data-cleanup-footer] button')].find(b=>b.textContent==='再扫描一次').click()")
  await waitFor("document.querySelector('input[type=password]')")
  assert.equal(await evaluate("document.querySelector('input[type=password]').value"), '')
  first.cleanup.applies.length = 0
  await enterPassword(); await ready(); await select(['apt-cache']); await confirm()
  await waitFor("document.querySelector('[data-cleanup-results]')")
  assert.equal(await evaluate("document.querySelector('[data-cleanup-incomplete]')"), null)
  await themes('results')
  await evaluate("await hopline.settings.update({language:'en'});await testState.reloadCatalog()")
  assert.ok((await cleanupText()).includes('Freed 64 MB'))
  assert.ok(!(await cleanupText()).includes('cleanup.'))
  await capture('results-dark-en')
  await evaluate("await hopline.settings.update({language:'zh'});await testState.reloadCatalog()")
  await click('[data-cleanup-footer] button.bg-accent'); await waitFor('!testState.getState().cleanupHost')
  await evaluate('testCleanupNav.openOpLog(fileHost.id)')
  await waitFor("document.querySelector('[data-cleanup-measurements]')")
  assert.ok(await evaluate("[...document.querySelectorAll('[data-cleanup-measurements]')].some(row=>row.innerText.includes('预计释放：64 MB') && row.innerText.includes('实际释放：64 MB'))"))
  await key('Escape'); await waitFor('!testState.getState().opLogHost')
  first.cleanup.mode = 'missing'
  await evaluate('testCleanupNav.openCleanup(fileHost.id)')
  await waitFor("document.querySelector('[data-cleanup-panel]')?.innerText.includes('当前不是 root 用户')")
  assert.equal(await evaluate("document.querySelectorAll('[data-cleanup-item]').length"), 0)
  await key('Escape')
  first.cleanup.mode = 'password'
  for (const kind of ['permission', 'check', 'du']) {
    first.cleanup.holdRead = kind
    await evaluate('testCleanupNav.openCleanup(fileHost.id)')
    if (kind !== 'permission') await waitFor("document.querySelector('[data-cleanup-panel] input[type=password]')")
    if (kind === 'check') await enterPassword()
    else if (kind === 'du') {
      await evaluate("document.querySelectorAll('[role=tab]')[1].click()")
      await evaluate("[...document.querySelectorAll('[data-cleanup-analysis] button')].find(b=>b.textContent==='分析目录').click()")
    }
    for (let tries=0; !first.cleanup.heldRead && tries<100; tries++) await delay(20)
    assert.ok(first.cleanup.heldRead)
    await evaluate("[...document.querySelectorAll('[data-cleanup-panel] button')].find(b=>b.textContent==='取消').click()")
    await waitFor("document.querySelector('[data-cleanup-panel] [role=alert]')?.innerText.includes('已取消')")
    await key('Escape'); await waitFor('!testState.getState().cleanupHost')
  }
  assert.equal(first.cleanup.stops, 4)
  for (const mode of ['root', 'nopass']) {
    first.cleanup.mode = mode
    await evaluate('testCleanupNav.openCleanup(fileHost.id)')
    await ready()
    assert.equal(await evaluate("!!document.querySelector('[data-cleanup-panel] input[type=password]')"), false, `Mode ${mode} scans without asking for a password`)
    await key('Escape'); await waitFor('!testState.getState().cleanupHost')
  }
  // Keep the real preview mounted, change its connection target, then confirm.
  // No stale command or administrator password may reach the replacement host.
  first.cleanup.mode = 'password'; first.cleanup.applies.length = 0
  await evaluate('testCleanupNav.openCleanup(fileHost.id)')
  await enterPassword(); await ready(); await select(['apt-cache'])
  const beforeTargetChange = { checks: first.cleanup.checks, applies: first.cleanup.applies.length, df: first.cleanup.dfReads }
  await evaluate('await hopline.hosts.save({...fileHost,port:1});await testState.reloadCatalog()')
  await confirm()
  await waitFor("document.querySelector('[data-cleanup-panel] [role=alert]')?.innerText.includes('主机连接配置已变化')")
  assert.equal(await evaluate("!!document.querySelector('[data-cleanup-confirm],[data-cleanup-ready],[data-cleanup-panel] input[type=password]')"), false)
  assert.deepEqual({ checks: first.cleanup.checks, applies: first.cleanup.applies.length, df: first.cleanup.dfReads }, beforeTargetChange)
  assert.ok(!(await cleanupText()).includes('cleanup-smoke-private'))
  await themes('target-changed')
  await evaluate('await hopline.hosts.save(fileHost);await testState.reloadCatalog()')
  await evaluate("[...document.querySelectorAll('[data-cleanup-footer] button')].find(b=>b.textContent==='再扫描一次').click()")
  await waitFor("document.querySelector('#kbd-form input') || document.querySelector('[data-cleanup-panel] input[type=password]')")
  if (await evaluate("!!document.querySelector('#kbd-form input')")) {
    await evaluate("document.querySelector('#kbd-form input').focus()")
    await browser.send('Input.insertText', { text: 'smoke-secret' }); await key('Enter')
  }
  await waitFor("document.querySelector('[data-cleanup-panel] input[type=password]')")
  assert.equal(await evaluate("document.querySelector('[data-cleanup-panel] input[type=password]').value"), '')
  await enterPassword(); await ready()
  await key('Escape'); await waitFor('!testState.getState().cleanupHost')
  console.log('PASS B38 stale cleanup authorization is rejected before SSH work; rescan rechecks permissions and requires a fresh password')
  assert.equal(first.cleanup.invalidStdin, 0); assert.equal(first.cleanup.commandLeaks, 0)
  assert.ok(!output().includes('cleanup-smoke-private'))
  first.cleanup.enabled = false
  console.log('PASS cleanup four screens, tri-state selection, unknown disabled, confirmation, isolated diagnostics, actual release, fresh password, cancel semantics and background result notification')
}
