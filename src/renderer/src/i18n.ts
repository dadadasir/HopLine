export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  if (isKeystoreReadError(key)) return KEYSTORE_UNREADABLE[locale]
  if (!zhReady) { zhReady = true; populateLabels(zh, null) }
  const table = locale === 'en' ? (enTable ??= (() => { const target = createEnBase(); populateLabels(null, target); return target })()) : zh
  let text = table[key] ?? zh[key] ?? key
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value))
  }
  return text
}

